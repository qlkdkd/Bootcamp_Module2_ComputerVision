import numpy as np

K = np.array([[800, 0, 320], [0, 800, 240], [0, 0, 1]], dtype=np.float64)    # 640x480에서 구한 값
s = 1280 / 640                                                       # 같은 카메라를 1280x960으로 쓸 때(가로세로 비율 같음)
K2 = K.copy()
K2[0, 0] *= s; K2[1, 1] *= s; K2[0, 2] *= s; K2[1, 2] *= s
print("640x480용  fx, fy, cx, cy:", K[0, 0], K[1, 1], K[0, 2], K[1, 2])
print("1280x960용 fx, fy, cx, cy:", K2[0, 0], K2[1, 1], K2[0, 2], K2[1, 2])
